def test_uninstall_runs_native_remove_commands(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path / "bin"))
    checkout = tmp_path / "demo"
    checkout.mkdir()
    (checkout / "ownbox.yaml").write_text(
        "name: demo\ndescription: Demo\ninstall:\n  remove: [python cleanup.py]\n"
    )
    launcher = create_launcher("demo")
    save_installations(
        {"demo": {"path": str(checkout), "repo": "me/demo", "launcher": str(launcher)}}
    )
    calls = []
    monkeypatch.setattr(
        "ownbox.store.subprocess.run", lambda command, **kwargs: calls.append((command, kwargs))
    )

    uninstall("demo", approve_commands=lambda commands: commands == ("python cleanup.py",))

    assert calls == [("python cleanup.py", {"cwd": checkout, "shell": True, "check": True})]
    assert not checkout.exists()


def test_update_prefers_native_update_commands_and_falls_back_to_setup(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path / "bin"))
    checkout = tmp_path / "demo"
    checkout.mkdir()
    manifest_path = checkout / "ownbox.yaml"
    manifest_path.write_text(
        "name: demo\ndescription: Demo\ninstall:\n"
        "  setup: [python setup.py]\n  update: [python update.py]\n"
    )
    save_installations({"demo": {"path": str(checkout), "repo": "me/demo"}})
    calls = []
    monkeypatch.setattr(
        "ownbox.store.subprocess.run", lambda command, **kwargs: calls.append((command, kwargs))
    )

    update("demo", approve_commands=lambda commands: commands == ("python update.py",))

    assert calls[0][0] == ["git", "-C", str(checkout), "pull", "--ff-only"]
    assert calls[1] == ("python update.py", {"cwd": checkout, "shell": True, "check": True})

    calls.clear()
    manifest_path.write_text(
        "name: demo\ndescription: Demo\ninstall:\n  setup: [python setup.py]\n"
    )

    update("demo", approve_commands=lambda commands: commands == ("python setup.py",))

    assert calls[1] == ("python setup.py", {"cwd": checkout, "shell": True, "check": True})


def test_update_refreshes_named_launchers(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path / "bin"))
    checkout = tmp_path / "demo"
    checkout.mkdir()
    manifest_path = checkout / "ownbox.yaml"
    manifest_path.write_text(
        "name: demo\ndescription: Demo\ncommands:\n  demo: bin/demo\n  helper: bin/helper\n"
    )
    old_launcher = create_launcher("demo")
    save_installations(
        {
            "demo": {
                "path": str(checkout),
                "repo": "me/demo",
                "launcher": str(old_launcher),
            }
        }
    )
    monkeypatch.setattr("ownbox.store.subprocess.run", lambda *args, **kwargs: None)

    update("demo")

    assert (tmp_path / "bin" / "demo").exists()
    assert (tmp_path / "bin" / "helper").exists()
    assert set(installations()["demo"]["launchers"]) == {"demo", "helper"}

    manifest_path.write_text(
        "name: demo\ndescription: Demo\ncommands:\n  demo: bin/demo\n  inspect: bin/inspect\n"
    )
    update("helper")

    assert not (tmp_path / "bin" / "helper").exists()
    assert (tmp_path / "bin" / "inspect").exists()


def test_windows_launcher_and_platform_directories(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "windows")
    monkeypatch.setenv("LOCALAPPDATA", str(tmp_path / "local"))
    monkeypatch.setenv("APPDATA", str(tmp_path / "roaming"))
    monkeypatch.delenv("OWNBOX_BIN_DIR", raising=False)

    from ownbox.store import bin_home, cache_home, config_home, data_home, launcher_path

    launcher = create_launcher("demo")

    assert data_home() == tmp_path / "local" / "ownbox"
    assert cache_home() == tmp_path / "local" / "ownbox" / "cache"
    assert config_home() == tmp_path / "roaming" / "ownbox"
    assert bin_home() == tmp_path / "local" / "ownbox" / "bin"
    assert launcher_path("demo").name == "demo.cmd"
    assert launcher.read_text() == (
        '@echo off\nrem generated by ownbox\nownbox "demo" %*\nexit /b %errorlevel%\n'
    )


def test_windows_install_runs_selected_setup_and_creates_cmd_launcher(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.manifest.platform.system", lambda: "Windows")
    monkeypatch.setenv("LOCALAPPDATA", str(tmp_path / "local"))
    monkeypatch.setenv("APPDATA", str(tmp_path / "roaming"))
    monkeypatch.delenv("OWNBOX_BIN_DIR", raising=False)
    monkeypatch.setattr("ownbox.store.shutil.which", lambda name: None)
    calls = []

    def fake_run(command, **kwargs):
        calls.append((command, kwargs))
        if isinstance(command, list) and command[:2] == ["git", "clone"]:
            (tmp_path / "checkout").mkdir()

    monkeypatch.setattr("ownbox.store.subprocess.run", fake_run)
    manifest = Manifest.from_text(
        r"""
name: demo
description: Demo
install:
  platforms: [windows]
  setup:
    windows: ['.venv\Scripts\python.exe -m pip install -e .']
command:
  windows: '.venv\Scripts\demo.exe'
""",
        "me/demo",
    )

    target = install(manifest, tmp_path / "checkout")

    assert target == tmp_path / "checkout"
    assert calls[1][0] == r".venv\Scripts\python.exe -m pip install -e ."
    assert calls[1][1]["shell"] is True
    assert (tmp_path / "local" / "ownbox" / "bin" / "demo.cmd").exists()
    assert installations()["demo"]["path"] == str(target)
