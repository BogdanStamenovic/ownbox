from ownbox.manifest import Manifest
from ownbox.store import (
    Catalog,
    create_launcher,
    install,
    installations,
    save_installations,
    uninstall,
    update,
)


def tool(name, description, tags=()):
    return Manifest(name=name, description=description, repo=f"me/{name}", tags=tags)


def test_catalog_searches_names_descriptions_and_tags():
    catalog = Catalog(
        "me",
        [tool("camera", "Take a photo", ("raspberry-pi",)), tool("notes", "Write things")],
        "now",
    )
    assert [item.name for item in catalog.find("photo")] == ["camera"]
    assert [item.name for item in catalog.find("raspberry")] == ["camera"]
    assert [item.name for item in catalog.find("camera")] == ["camera"]


def test_catalog_round_trip(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path))
    catalog = Catalog("me", [tool("demo", "Demo")], "now")
    catalog.save()
    loaded = Catalog.load()
    assert loaded is not None
    assert loaded.owner == "me"
    assert loaded.tools[0].name == "demo"


def test_launcher_routes_through_ownbox(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path))
    launcher = create_launcher("demo")
    assert launcher.read_text() == "#!/bin/sh\n# generated by ownbox\nexec ownbox 'demo' \"$@\"\n"
    assert launcher.stat().st_mode & 0o111


def test_install_creates_every_named_launcher(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path / "bin"))
    monkeypatch.setattr("ownbox.store.shutil.which", lambda name: None)
    target = tmp_path / "checkout"

    def fake_run(command, **kwargs):
        if isinstance(command, list) and command[:2] == ["git", "clone"]:
            target.mkdir()

    monkeypatch.setattr("ownbox.store.subprocess.run", fake_run)
    manifest = Manifest(
        name="demo",
        description="Demo",
        repo="me/demo",
        commands={"demo": "bin/demo", "helper": "bin/helper"},
    )

    install(manifest, target)

    assert (tmp_path / "bin" / "demo").exists()
    assert (tmp_path / "bin" / "helper").exists()
    assert set(installations()["demo"]["launchers"]) == {"demo", "helper"}


def test_uninstall_by_alias_removes_every_launcher(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "data"))
    monkeypatch.setenv("OWNBOX_BIN_DIR", str(tmp_path / "bin"))
    checkout = tmp_path / "demo"
    checkout.mkdir()
    (checkout / "ownbox.yaml").write_text(
        "name: demo\ndescription: Demo\ncommands:\n  demo: bin/demo\n  helper: bin/helper\n"
    )
    launchers = {
        "demo": str(create_launcher("demo")),
        "helper": str(create_launcher("helper")),
    }
    save_installations({"demo": {"path": str(checkout), "repo": "me/demo", "launchers": launchers}})

    uninstall("helper")

    assert not checkout.exists()
    assert not (tmp_path / "bin" / "demo").exists()
    assert not (tmp_path / "bin" / "helper").exists()


def test_uninstall_removes_checkout_launcher_and_registration(tmp_path, monkeypatch):
    monkeypatch.setattr("ownbox.store.current_platform", lambda: "linux")
